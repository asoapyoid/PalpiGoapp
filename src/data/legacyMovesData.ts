// Ultra-fast O(1) species and pre-evolution lookup map to keep RAM light and prevent repeated array scans
const LEGACY_MOVES_MAP = new Map<string, LegacyEvolutionMove>();
for (const entry of LEGACY_MOVES_DATA) {
  // Index all species name parts (e.g. "Dipplin / Hydrapple")
  for (const part of entry.speciesName.toLowerCase().split(/[\s/]+/)) {
    if (part && part.length > 2) LEGACY_MOVES_MAP.set(part, entry);
  }
  // Index all words in preEvolution (e.g. "Metang (from Beldum)" -> "metang", "beldum")
  const words = entry.preEvolution.toLowerCase().match(/[a-z0-9]+/g) || [];
  for (const w of words) {
    if (w !== 'from' && w.length > 2) {
      LEGACY_MOVES_MAP.set(w, entry);
    }
  }
  // Also index from searchString (e.g. "+beldum&!@special" -> "beldum")
  const searchMatch = entry.searchString.match(/\+([a-z0-9]+)/i);
  if (searchMatch && searchMatch[1]) {
    LEGACY_MOVES_MAP.set(searchMatch[1].toLowerCase(), entry);
  }
}

/**
 * Returns the Legacy Move info for a given species or pre-evolution in O(1) time.
 */
export function getLegacyEvolutionInfo(pokemonName: string): LegacyEvolutionMove | null {
  if (!pokemonName) return null;
  const clean = pokemonName.trim().toLowerCase();
  if (LEGACY_MOVES_MAP.has(clean)) {
    return LEGACY_MOVES_MAP.get(clean)!;
  }
  const firstWord = clean.split(/[\s/]+/)[0];
  return LEGACY_MOVES_MAP.get(firstWord) || null;
}

/**
 * Returns all currently active event moves.
 */
export function getActiveLegacyMoves(): LegacyEvolutionMove[] {
  return LEGACY_MOVES_DATA.filter((m) => m.isCurrentlyActive);
}
